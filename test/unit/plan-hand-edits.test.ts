/* ------------------------------------------------------------------ */
/* A real hand edit is still detected                                  */
/* ------------------------------------------------------------------ */

test("a line added by hand inside the managed block is still detected", async () => {
  const h = await createTmpHome("gs-handedits-");
  try {
    await seedApplied(h.home, twoRules(h.home));
    const text = await h.read(".gitconfig");
    await h.write(
      ".gitconfig",
      text.replace(BEGIN_MARKER, `${BEGIN_MARKER}\n# my own note`),
    );

    const next = await plan({ home: h.home, profiles: twoRules(h.home) });
    assert.equal(
      next.errors.length,
      1,
      `expected a hand-edit error, got: ${next.errors.join(" | ")}`,
    );
    assert.match(next.errors[0] as string, /edits gs did not generate/);
    assert.match(
      next.errors[0] as string,
      /my own note/,
      "the error has to name the offending line",
    );
  } finally {
    await h.cleanup();
  }
});

test("a hand-edited line inside ~/.ssh/config is detected and named", async () => {
  const h = await createTmpHome("gs-handedits-");
  try {
    await seedApplied(h.home, twoRules(h.home));
    const text = await h.read(".ssh/config");
    await h.write(
      ".ssh/config",
      text.replace("Host work", "Host work\n\tProxyJump bastion.example"),
    );

    const next = await plan({ home: h.home, profiles: twoRules(h.home) });
    assert.equal(
      next.errors.length,
      1,
      `expected a hand-edit error, got: ${next.errors.join(" | ")}`,
    );
    assert.match(next.errors[0] as string, /ProxyJump bastion\.example/);
  } finally {
    await h.cleanup();
  }
});
